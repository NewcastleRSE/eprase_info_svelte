   <p class='question'>Q: Can we have access to all the questions and the raw data?</p>

    <p class='answer'>A: Users do get more detail test descriptions and direct feedback on mandatory questions.</p>

    <p>We are unable to share raw data or general scenario details as we need to protect the integrity of the ePRaSE tool assessments. </p>

    <p class='question'>Q: Will you share any learning from this version rollout with vendors?</p>

    <p class='answer'>A: System suppliers (vendors) do not currently have access to the tool, however the ePRaSE team have started sharing high level anonymised results with some vendors as part of the improvement work.</p>

    <p class='question'>Q: Will you share any learning from this version rollout with users?</p>

    <p class='answer'>A: Anonymised user result summaries are published on <a class="linelink" href={resolve("/results/2025")}>this site</a> at the end of each cycle as soon as the team have processed the data (typically March/April). Thematic findings will be shared through the ePrescribing Masterclasses, publications, and other events. Masterclasses can be accessed by signing up via <a class="linelink" href="mailto:england.digitalmedicines@nhs.net" title="mailto:england.digitalmedicines@nhs.net">england.digitalmedicines@nhs.net</a>. National results have also enabled the team to build a <a class="linelink" href={resolve("/lab")}>Learning Lab toolkit</a> to support users in optimising their systems.</p>

    <p class='question'>Q: Is the tool designed for acute trust scenarios only?</p>

    <p class='answer'>A: Thecurrent version is designed for use by acute specialist, general district, and mental health trusts. Users can now do both an adult and a separate paediatric assessment for each EP system deployed their trust. If both systems are used, then both assessments should be completed. Please work through each assessment one at a time i.e., complete one assessment fully before starting the next. </p>

    <p class='question'>Q: Do we complete the test if we have recently implemented the EPMA system?</p>

    <p class='answer'>A: Yes, you can -- when completing you will enhance your learning, and it may provide a helpful baseline at this early stage of your electronic prescribing journey.</p>

    <p class='question'>Q: Why am I unable to access the tool using my nhs.uk domain?</p>

    <p class='answer'>A: The tool can only be accessed currently from within an NHS network (HSCN), to users with nhs.net or nhs.uk email accounts. There is no 'public' access from anywhere (unless you are connected to your NHS network remotely). This means that unless you have remote access set up from a device you cannot use at home, access will be limited to inside your work locations. If you are at a work location and still unable to get access, you will need to log a ticket with your IT support team and get them to check if there is a firewall blocking the domain. Home Nations not on the HSCN are unable to use the tool. We are working on a solution, please bear with us.</p>

    <p class='question'>Q:Why is the tool hosted on the HSCN?</p>

    <p class='answer'>A:The NHS-sponsored ePRaSE tool is hosted on the Health and Social Care Network (HSCN), a secure infrastructure specifically designed to safeguard sensitive patient information and mitigate cyber threats. In light of the increased risk of cyberattacks targeting healthcare and other critical national services, it has been determined that it will be safer for Trusts for the tool to continue to be hosted on HSCN. Consequently, we are reviewing mechanisms to enable home nations to access HSCN for the purpose of completing the assessment.</p>

    <p class='question'>Q: Can we amend a response that has been incorrectly added?</p>

    <p class='answer'>A: Once you have submitted a response for a test scenario you cannot go back and amend the response. Please contact us at <a class="linelink" href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a> if you require further support.</p>

    <p class='question'>Q: What can we do if we missed important information in our patient build and the tool seems to have lost the information we added?</p>

    <p class='answer'>A: If you have missed important information in your patient build you can go back and view the patient build again. However, please contact us at <a class="linelink" href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a> if you need further assistance or your tests reset.</p>

    <p class='question'>Q: We use more than one electronic prescribing system in our organisation. Can you amend the tool to include these changes?</p>

    <p class='answer'>A: The current version allows users to test more than one different EP system, if in use in their organisation.</p>

    <p class='question'>Q: Who can complete the assessment?</p>

    <p class='answer'>A: The assessment can be completed by an individual or teams who have the access and capability to be able to use their electronic prescribing system to admit/edit patients and prescribe medicines.</p>

    <p class='question'>Q: Do we have to admit in Patient Administration System (PAS)? Or can we admit manually in the EPMA system directly as this is easier for us to manage locally?</p>

    <p class='answer'>A: We recommend following your normal operating procedure. If patient information is drawn from PAS into the electronic prescribing system normally, we would recommend that you do that. Some patients require additional clinical or general information such as GP name to be added for the scenarios/test to work correctly. Please use whatever standard dummy information you would normally use to test your systems. We estimate it takes 1-2 hours to set up the fictional patients and similar time to run the test part and record observations. You can log in and out of the patient build sections without losing your place so that it can be completed over several different sessions if that is easier.</p>

    <p class='question'>Q: Can anyone outside the ePRaSE project team view the identifiable data via this tool?</p>

    <p class='answer'>A: Individuals outside of the ePRaSE Project Team cannot view identifiable data via this tool.</p>

    <p class='question'>Q: Why are my results not as expected?</p>

    <p class='answer'>A: We understand that the scoring system will not be perfect at the outset. We will be analysing factors from all the collected data as part of NHS England's drive for patient safety.</p>

    <p class='question'>Q: I have completed the tool assessment. However, I do not understand the report I have been provided. Is there support to help with the results?</p>

    <p class='answer'>A: If you have any queries with your report, please refer to the user guide or contact <a class="linelink" href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a> for support.</p>

    <p class='question'>Q: I have used ePRaSE before, do I have to sign up again?</p>

    <p class='answer'>A: The ePRaSE tool is completely refreshed annually and all users will have to register even if they have signed up to the previous version.</p>

    <p class='question'>Q: I have used ePRaSE before, can I access the reports from last time?</p>

    <p class='answer'>A: The ePRaSE tool has been completely refreshed and reports generated by users in the last version cannot be recalled. The new tool allows reports to be printed off and exported for future reference.</p>

    <p class='question'>Q: I need technical support, when can I get in touch?</p>

    <p class='answer'>A: Please contact us by email at <a class="linelink" href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a>. Office times are 9am-5pm. Response times are from 48 hours to 72 hours.</p>

    <p class='question'>Q: Is it possible to access the tool and carry out a test run before completing the proper assessment?</p>

    <p class='answer'>A: The ePRaSE assessment is an annual test that can only be completed by an individual Trust once. It is not possible to go in and have a look and do multiple runs. Please refer to the explainer videos and user guide to prepare ahead of the self-assessment, both available here at <a class="linelink" href={resolve("/using")}>eprase.info</a>.</p>

    <p class='question'>Q: How many times can we test our systems?</p>

    <p class='answer'>A: The ePRaSE Tool assessment is planned as an annual test. Users can now do both an adult and a separate paediatric assessment for each EP system deployed their trust. If both systems are used, then both assessments should be completed. Please work through each assessment one at a time i.e., complete one assessment fully before starting the next.</p>

    <p class='question'>Q: How do we complete the general question about whole time equivalents involved in maintaining multiple EP systems? </p>

    <p class='answer'>A: For those completing both paediatric and adult assessments for the same or multiple different adult EP systems please estimate the proportion of staff time committed to each i.e., record estimated WTE per each individual EP system.</p>

