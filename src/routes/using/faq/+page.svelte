		<summary class="section-head">3. Starting an Assessment</summary>
		<div class="section-content"><div>
			<details class="faq-item">
				<summary class="question">3.1 Can multiple users work on the same assessment?</summary>
				<div class="answer"><div>
					<p>Yes. Up to four registered users can contribute to the same assessment. However, only one user should actively edit the assessment at any one time.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.2 Can we assess more than one prescribing system?</summary>
				<div class="answer"><div>
					<p>Yes. The 2026 version supports multiple ePrescribing systems within the same organisation. Separate assessments should be completed for each system.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.3 Can we complete both Adult and Paediatric assessments?</summary>
				<div class="answer"><div>
					<p>Yes. Organisations can undertake both Adult and Paediatric assessments for each ePrescribing system deployed within their Trust.</p>
					<p>If your ePrescribing system is used in both adult and paediatric settings, both assessments should be completed.</p>
					<p>For the best experience and most accurate results, complete each assessment in full before starting the next (for example, complete the adult assessment before beginning the paediatric assessment).</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.4 Can we complete an assessment on behalf of another organisation?</summary>
				<div class="answer"><div>
					<p>Yes. The assessment includes functionality to identify when testing is being completed on behalf of another Trust or organisation.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.5 Can I save my progress and return later?</summary>
				<div class="answer"><div>
					<p>Yes. Progress is saved throughout the assessment, and you can log out and return later.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.6 I can't find my assessment after logging back in.</summary>
				<div class="answer"><div>
					<p>Go to the Assessment Selection screen and select your existing assessment. Many users mistakenly start a new assessment instead of continuing an existing one.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.7 Is it possible to access the tool and carry out a test run before completing the proper assessment?</summary>
				<div class="answer"><div>
					<p>Yes. Before starting the live ePRaSE assessment, users can complete a Practice Session designed to familiarise themselves with the assessment process.</p>
					<p>The Practice Session allows users to create a test patient, work through a sample prescribing scenario and practise recording outcomes using the same workflow as the live assessment. This provides an opportunity to gain confidence with the system before completing the scored assessment.</p>
					<p>The Practice Session is not scored, does not contribute to organisational results and can be repeated as often as required.</p>
					<p>However, the live ePRaSE assessment can only be completed once per Trust each year. It is therefore not possible to access the live assessment for a trial run or complete multiple submissions.</p>
					<p>To prepare in advance, we recommend reviewing the explainer videos and user guide available at eprase.info and completing the Practice Session before beginning the live assessment.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.8 How many times can we test our systems?</summary>
				<div class="answer"><div>
					<p>The ePRaSE assessment is designed to be completed annually. Organisations can undertake both Adult and Paediatric assessments for each ePrescribing system deployed within their Trust.</p>
					<p>If your ePrescribing system is used in both adult and paediatric settings, both assessments should be completed.</p>
					<p>For the best experience and most accurate results, complete each assessment in full before starting the next.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.9 Who can complete the assessment?</summary>
				<div class="answer"><div>
					<p>The assessment can be completed by an individual or a team who have the access and capability required to use their electronic prescribing system to admit/edit patients and prescribe medicines.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">3.10 How do we complete the general question about whole-time equivalents involved in maintaining multiple ePrescribing systems?</summary>
				<div class="answer"><div>
					<p>For organisations completing both Adult and Paediatric assessments for the same system or assessments for multiple ePrescribing systems: Please estimate the proportion of staff time committed to each system and record the estimated WTE against each individual ePrescribing system.</p>
					<p>For example: If you have six whole-time equivalents (WTEs) looking after your organisation's electronic prescribing system, and approximately two-thirds of their time is spent updating and maintaining the adult system, with one-third spent supporting the paediatric system, then you would record four WTEs under adults and two WTEs under paediatrics.</p>
				</div></div>
			</details>
		</div></div>
