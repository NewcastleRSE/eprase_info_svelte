				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.4 What does "Prescribing completed with no system/user intervention" mean?</summary>
				<div class="answer"><div>
					<p>You placed the order for the new medicine using your normal processes, which may have included the selection of a provided order sentence and did not receive any advice or information from the electronic prescribing system.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.5 What does "Prescribing completed but had to override components of the order sentence" mean?</summary>
				<div class="answer"><div>
					<p>You placed the order for the new medicine but had to ignore, modify, or override a provided order sentence to complete it.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.6 What does "Prescribing completed with system/user intervention" mean?</summary>
				<div class="answer"><div>
					<p>You prescribed the medicine and received some system generated clinical decision support, alerts, warnings or other information that directed you to make a decision to modify the prescription.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.7 What does "Prescribing Prevented" mean?</summary>
				<div class="answer"><div>
					<p>The ePrescribing system blocks completion of the prescriptions entirely with no prescriber action possible. It is clear cut and the prescription cannot be executed.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.8 What does "Unable to perform test" mean?</summary>
				<div class="answer"><div>
					<p>Where the medicine presented in the test is not available in your system, the question will be passed over. This will be classed as an invalid test. It will not affect the overall mitigation results which are calculated on the valid tests taken.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">6.9 What happens if the medicine is unavailable in my system?</summary>
				<div class="answer"><div>
					<p>Select "Unable to Perform Test". This will not negatively influence your mitigation score.</p>
				</div></div>
			</details>
		</div></div>
