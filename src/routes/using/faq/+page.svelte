		<summary class="section-head">9. Reports and Results</summary>
		<div class="section-content"><div>
			<details class="faq-item">
				<summary class="question">9.1 What does the final report show?</summary>
				<div class="answer"><div>
					<p>Reports include:</p>
					<ul>
						<li>Summary risk mitigation performance chart.</li>
						<li>Overview of results within prescribing risk category.</li>
						<li>Mandatory scenario outcomes and improvement advice</li>
						<li>Mitigations chart showing scores within clinical decision (CDS) support categories for user analysis</li>
