		<summary class="section-head">7. Clinical Decision Support (CDS)</summary>
		<div class="section-content"><div>
			<details class="faq-item">
				<summary class="question">7.1 What are CDS categories?</summary>
				<div class="answer"><div>
					<p>Clinical Decision Support (CDS) Categories form the basis of the ePRaSE mitigation analysis and help organisations understand how effectively their ePrescribing system supports safe prescribing practices across a broad range of clinical risk areas.</p>
					<p>The following categories are used:</p>
					<ul>
						<li><strong>Anti-Microbial Stewardship:</strong> Drug triggers recommendations on antimicrobial prescription support/guidelines and surveillance related to management of antimicrobial resistance.</li>
						<li><strong>Drug Age:</strong> Drug contraindication (or dose adjustment) based on patient age.</li>
						<li><strong>Drug Allergy:</strong> Allergy or intolerance to prescribed drug (or another drug in the same category) documented.</li>
						<li><strong>Drug Brand:</strong> Drug that must be prescribed by BRAND rather than using generic name.</li>
						<li><strong>Drug-Disease (Contraindication):</strong> Drug contraindication (or dose adjustment) based on patient diagnosis or co-morbidities.</li>
						<li><strong>Drug Dose:</strong> Specified dose for prescribed drug is outside recommended dose range for any patient (includes doses that are too high or too low).</li>
						<li><strong>Drug Duplication:</strong> Specified drug prescribed more than once for the same patient.</li>
						<li><strong>Drug Frequency:</strong> Specified frequency is not appropriate for prescribed drug.</li>
						<li><strong>Drug Laboratory:</strong> Drug contraindication (or dose adjustment) based on laboratory test result (includes therapeutic drug monitoring, direct notification/ display of abnormal labs; dosing suggestions; monitoring advisory or monitoring order request).</li>
						<li><strong>Drug Omission:</strong> Critical medication NOT prescribed based upon patient diagnosis or other prescribed medication.</li>
						<li><strong>Drug-Drug Interaction:</strong> Interaction between prescribed drug and one or more concomitant prescribed drug(s) may result in patient harm.</li>
						<li><strong>Drug Route:</strong> Specified route is contraindicated for drug and/or dose prescribed.</li>
						<li><strong>Pregnancy Prevention:</strong> Drug prescribed requires safety measures due to reproductive risks.</li>
						<li><strong>Therapeutic Duplication:</strong> Two different medicines prescribed simultaneously with the same or similar therapeutic aims.</li>
					</ul>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">7.2 How many CDS categories can I choose?</summary>
				<div class="answer"><div>
					<p>Up to two categories can be selected for each test triggering an intervention.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">7.3 What if I'm unsure which category applies?</summary>
				<div class="answer"><div>
					<p>Select the category that most closely represents the main intervention observed. There are no right or wrong answers, and this does not impact your overall mitigation score.</p>
				</div></div>
