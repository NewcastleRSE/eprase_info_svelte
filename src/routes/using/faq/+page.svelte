		<div class="section-content">
            <div>
			<details class="faq-item">
				<summary class="question">1.1 What is ePRaSE?</summary>
				<div class="answer"><div>
					<p>ePRaSE (ePrescribing Risk and Safety Evaluation) is a web-based assessment tool designed to help NHS organisations evaluate the safety and effectiveness of their electronic prescribing (EPMA) systems using fictional test patients and prescribing scenarios.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">1.2 Why should our organisation complete ePRaSE?</summary>
				<div class="answer"><div>
					<p>ePRaSE provides an objective review of how effectively an electronic prescribing system mitigates prescribing risks and highlights opportunities for optimisation and safety improvement.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">1.3 Do we need to participate if our ePrescribing system is newly implemented?</summary>
				<div class="answer"><div>
					<p>Yes. New implementations can benefit from establishing a baseline safety position and identifying enhancement opportunities early in their digital prescribing journey.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">1.4 Is ePRaSE only for acute hospitals?</summary>
				<div class="answer"><div>
					<p>No. The tool can be used by acute, specialist, district general and mental health organisations that use electronic prescribing systems.</p>
				</div></div>
			</details>
            </div>
		</div>
	</details>

