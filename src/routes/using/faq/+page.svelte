				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.2 What are mandatory scenarios?</summary>
				<div class="answer"><div>
					<p>These are high-priority patient safety tests that all organisations are expected to assess.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.3 What is deception analysis?</summary>
				<div class="answer"><div>
					<p>The tool includes control scenarios designed to identify inappropriate alerts and false positives. This evaluates the quality of system decision support, not simply the quantity of alerts.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.4 Can I print my report?</summary>
				<div class="answer"><div>
					<p>Yes. Reports can be exported as PDF documents for local review and retention.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.5 Can I see reports from previous years?</summary>
				<div class="answer"><div>
					<p>Historical reports, where available, can be selected for your organisation from 'Assessment Selection' page.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.6 Can I have access to all the questions and my raw assessment data?</summary>
				<div class="answer"><div>
					<p>In the latest version of ePRaSE, users are provided with enhanced test descriptions and direct feedback on mandatory scenarios. However, detailed feedback is not provided for all scenarios, as doing so would undermine the integrity of the assessment and could encourage optimisation targeted only at individual test cases. The aim of ePRaSE is to support a broader, system-wide approach to ePrescribing optimisation by promoting robust prescribing infrastructure, effective multidisciplinary use of the system, appropriate alert design and acuity, and clear, meaningful decision support. The focus is on strengthening overall medicines safety processes rather than addressing isolated scenario-specific events.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.7 Can I compare my results against other organisations?</summary>
				<div class="answer"><div>
					<p>Yes. Organisations may choose to share their own results with peers or system suppliers to support learning and improvement through local or regional benchmarking meetings. Any data the ePRaSE team share outside your organisation is anonymised, and organisations are not identified in reports or dashboards. If you have questions about data use or governance, please contact <a href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a>.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.8 Why are my results not as expected?</summary>
				<div class="answer"><div>
					<p>There are several reasons why your results may differ from what you anticipated. The patient build may not have been completed exactly as intended, some information may not have been available within your ePrescribing system, or local system configuration and clinical decision support settings may have influenced the outcome.</p>
					<p>ePRaSE reflects how your electronic prescribing system functions in practice based on the way it has been configured, implemented, and maintained within your organisation. As a result, unexpected findings can help identify areas for review and optimisation.</p>
					<p>The purpose of ePRaSE is not only to generate a score, but to help organisations understand what is working well within their ePrescribing system and where opportunities may exist to further improve medication safety.</p>
				</div></div>
			</details>

			<details class="faq-item">
				<summary class="question">9.9 I have completed the tool assessment but do not understand the report I have been provided. Is support available to help with the results?</summary>
				<div class="answer"><div>
					<p>If you have any queries about your report, please refer to the user guide, which provides an overview of the report structure. You can also access the 'Responding to ePRaSE' video in the 'Using ePRaSE' section of the eprase.info website, which explains the report and next steps to take from a user perspective.</p>
					<p>If you require further help, please contact <a href="mailto:nuth.eprase@nhs.net">nuth.eprase@nhs.net</a>.</p>
